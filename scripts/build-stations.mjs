// Regenerate src/js/data/all-stations.js from the open datameet railways dataset.
// Usage: node scripts/build-stations.mjs   (downloads ~2 MB from GitHub)
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "js", "data", "all-stations.js");
const URL_ = "https://raw.githubusercontent.com/datameet/railways/master/stations.json";

const titleIfUpper = (s) => (s === s.toUpperCase() ? s.toLowerCase().replace(/\b[a-z]/g, (c) => c.toUpperCase()) : s);
const round3 = (n) => Math.round(n * 1000) / 1000;

/** GeoJSON features -> [[code, name, lat, lon, state], ...], keeping valid points inside India. */
export function toStationRows(geojson) {
  const seen = new Set();
  const rows = [];
  for (const f of geojson.features || []) {
    const p = f.properties || {};
    const code = String(p.code || "")
      .trim()
      .toUpperCase();
    const name = String(p.name || "").trim();
    if (!code || code.startsWith("XX") || !/^[A-Z0-9]{1,6}$/.test(code) || seen.has(code)) continue;
    const [lon, lat] = f.geometry?.coordinates || [];
    if (!(lat > 6 && lat < 37 && lon > 68 && lon < 98)) continue;
    seen.add(code);
    rows.push([code, titleIfUpper(name), round3(lat), round3(lon), p.state || ""]);
  }
  return rows;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const res = await fetch(URL_);
  if (!res.ok) throw new Error(`Download failed: HTTP ${res.status}`);
  const rows = toStationRows(await res.json());
  const json = JSON.stringify(rows);
  if (json.includes("</")) throw new Error("station names contain '</', which would break the bundled page");
  writeFileSync(
    OUT,
    "// Generated by scripts/build-stations.mjs from the datameet railways dataset. Do not edit by hand.\n" +
      "// Each entry: [code, name, latitude, longitude, state].\n" +
      `export const ALL_STATIONS = ${json};\n`,
  );
  console.log(`Wrote ${rows.length} stations to ${OUT.slice(ROOT.length + 1)}`);
}
